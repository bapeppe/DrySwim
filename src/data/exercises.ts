export const exercises: Exercise[] = rows.map(
  ([
    id,
    name,
    category,
    defaultSets,
    amount,
    mode,
    sides,
    muscles,
    start,
    move,
    finish,
    mistake,
    easier,
    harder,
    difficulty = 'beginner',
    equipment = 'Corpo libero',
    positions = 1,
  ]) => {
    const cats: ExerciseCategory[] = [category];
    if (id === 'scapular-push-up') cats.push('parte-superiore');
    if (id === 'shoulder-taps') cats.push('core');
    if (id === 'hollow-hold') cats.push('coordinazione');
    const jump = category === 'esplosivita';
    const dose: Dose = {
      mode,
      ...(mode === 'time' ? { durationSeconds: amount } : { reps: amount }),
      sides,
      positions,
      secondsPerRep: id === 'tempo-squat' ? 5 : jump ? 5 : 3,
    };
    const safetyNotes = [
      'Interrompi se senti dolore, capogiri o fastidio articolare. Respira e conserva sempre una tecnica controllata.',
      ...(category === 'flessibilita'
        ? ['Cerca solo una tensione lieve: niente rimbalzi, spinte esterne o stretching doloroso.']
        : []),
      ...(jump
        ? [
            'Atterra in modo silenzioso flettendo anche e ginocchia, con ginocchia in linea con piedi e caviglie. Recupera almeno 60–90 secondi, anche di più se necessario. Non saltare fino al cedimento; fermati se peggiora la tecnica.',
          ]
        : []),
    ];
    if (id === 'towel-row')
      safetyNotes.push(
        'Nessun punto di ancoraggio. È un’attivazione isometrica auto-resistita: non equivale a un rematore con resistenza esterna. Evita asciugamani elastici o danneggiati.',
      );
    return exerciseSchema.parse({
      id,
      slug: id,
      name,
      categories: cats,
      muscleGroups: muscles.split(','),
      difficulty,
      description: `${move} ${finish}`,
      objective: jump
        ? 'Esprimere una spinta rapida con atterraggio controllato.'
        : category === 'flessibilita'
          ? 'Mantenere una tensione muscolare lieve e confortevole.'
          : `Allenare ${muscles.toLocaleLowerCase('it')} con un movimento controllato.`,
      swimmingBenefits: cats.map((c) => categories[c].benefit),
      instructions: [start, move, finish],
      commonMistakes: [mistake],
      safetyNotes,
      prerequisites: jump
        ? [
            'Approvazione dell’allenatore e riscaldamento completato.',
            'Squat e atterraggio su due piedi controllati, senza dolore.',
            ...(difficulty === 'advanced'
              ? [
                  'Equilibrio monopodalico e salti di base stabili; apprendere il gesto con l’allenatore prima dell’uso autonomo.',
                ]
              : []),
          ]
        : id === 'pike-push-up'
          ? ['Push-up e tenuta della posizione a V controllati; apprendimento con l’allenatore.']
          : [],
      easierVariation: easier,
      harderVariation: harder,
      defaultSets,
      dose,
      restSeconds: jump ? 75 : category === 'flessibilita' ? 10 : 30,
      equipment: [equipment],
      youtubeVideoId: videoRegistry[id]?.youtubeVideoId,
      youtubeSearchQuery: `${name} esercizio tecnica`,
    });
  },
);
